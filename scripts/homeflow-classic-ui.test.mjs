import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const source=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const app=source('src/App.vue')
const access=source('src/StudyHomeFlowAccess.vue')
const practical=source('src/StudyHomeFlowPractical.vue')
const dictionary=source('src/StudyHomeFlowDictionary.vue')
const exams=source('src/StudyHomeFlowExams.vue')
const language=source('src/StudyHomeFlowLanguage.vue')
const worker=source('worker/homeflow-practical.ts')
const routes=source('worker/index.ts')
const migration=source('migrations/0193_homeflow_scenario_attempts.sql')

test('all four original navigation modules remain present for SSO',()=>{
 for(const id of ['exam','practical','language','dictionary'])
  assert.ok(app.includes("id: '"+id+"' as const"),'missing original module '+id)
 assert.match(access,/StudyHomeFlowExams/)
 assert.match(access,/StudyHomeFlowPractical/)
 assert.match(access,/StudyHomeFlowLanguage/)
 assert.match(access,/StudyHomeFlowDictionary/)
 assert.match(access,/defineProps<\\{activeModule\\?:StudyModule\\}>/)
 assert.match(app,/<template v-if="homeflowIdentityUser">/)
 assert.match(app,/<template v-else>\s*<StudyHomeFlowAccess v-if="activeModule==='home'"/)
})
test('classic exam/language/practical/dictionary use original visual elements',()=>{
 assert.match(exams,/class="exam-list"/)
 assert.match(exams,/class="exam-card"/)
 assert.match(language,/class="language-banner"/)
 assert.match(language,/class="language-choice"/)
 assert.match(language,/language-study-card/)
 assert.match(language,/vocabulary_expansion_json/)
 assert.match(practical,/class="question-card practical-scenario-card"/)
 assert.match(practical,/ExamScratchTools/)
 assert.match(dictionary,/class="dictionary-search"/)
 assert.match(dictionary,/class="dictionary-card"/)
 assert.match(dictionary,/class="saved-vocabulary-list"/)
})
test('SSO practical writes are actor-scoped with no legacy table edits',()=>{
 assert.match(worker,/verifiedStudyActor\(req,env\)/)
 assert.match(worker,/body.expected_user_id!==actor.user_id/)
 assert.match(worker,/homeflow_scenario_attempts/)
 assert.match(worker,/ON CONFLICT\(homeflow_user_id,id\) DO NOTHING/)
 assert.match(worker,/WHERE homeflow_user_id=\? AND id=\?/)
 assert.doesNotMatch(worker,/INSERT INTO scenario_attempts|UPDATE scenario_attempts/)
 assert.match(routes,/return homeflowPractical\(request, env\)/)
 assert.match(migration,/PRIMARY KEY\(homeflow_user_id,id\)/)
 assert.match(migration,/IMMUTABLE_PERSONAL_SCENARIO_ATTEMPT/)
})
test('SSO dictionary cannot reuse legacy localStorage and confirms actor before saving',()=>{
 assert.doesNotMatch(dictionary,/localStorage\.|sessionStorage\.|indexedDB\./)
 assert.match(dictionary,/expected_user_id:actor/)
 assert.match(dictionary,/data.actor_user_id!==actor/)
 assert.match(dictionary,/\/api\/homeflow-study\/vocabulary/)
 assert.doesNotMatch(dictionary,/\/api\/vocabulary\/saved/)
 assert.match(dictionary,/\/api\/dictionary\?/)
})
test('original owner migration does not make legacy cache accessible to household members',()=>{
 assert.match(app,/const LEGACY_QUARANTINE='zhixue:legacy-cache-quarantine-v1'/)
 assert.match(app,/function legacyWritesAllowed\(\)\{/)
 assert.match(app,/!homeflowIdentityUser.value/)
 assert.doesNotMatch(practical,/localStorage\.|sessionStorage\.|indexedDB\./)
 assert.doesNotMatch(dictionary,/localStorage\.|sessionStorage\.|indexedDB\./)
})
